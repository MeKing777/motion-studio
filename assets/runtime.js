	function setupAnim(el, rule) {
		var a = rule.anim || {}, l = rule.loop;
		var startLoop = function () {
			if (l && l.type && (l.trigger || 'always') === 'always') playLoop(el, l);
		};

		if (l && l.type && l.trigger === 'hover') bindHover(el, function () { playLoop(el, l, true); });
		if (l && l.type && l.trigger === 'click') {
			var lc = function () { playLoop(el, l, true); };
			el.addEventListener('click', lc); onCleanup(el, function () { el.removeEventListener('click', lc); });
		}

		if (!a.in && !a.out) { startLoop(); return; }

		var trig = a.trigger || 'scroll';
		var afterIn = function () {
			startLoop();
			if (a.out && a.outTrigger === 'delay') {
				var t = setTimeout(function () { playOut(el, a); }, num(a.outDelay, 3000));
				onCleanup(el, function () { clearTimeout(t); });
			}
		};

		if (a.in) {
			if (trig === 'load') playIn(el, a, afterIn);
			else if (trig === 'scroll') {
				var thr = a.offset != null ? num(a.offset, 0.15) : num(SET.offset, 0.15);
				observe(el, function (en) {
					if (en.isIntersecting) {
						if (el._msState !== 'in') playIn(el, a, afterIn);
					} else if (el._msState === 'in' && en.boundingClientRect.top > 0 && a.once === false) {
						// Scrolled back up past it → reset so it replays.
						cancelAnims(el); el._msState = null;
						el.style.removeProperty('opacity');
						if (a.out && a.outTrigger === 'leave') playOut(el, a);
					} else if (el._msState === 'in' && a.out && a.outTrigger === 'leave') {
						playOut(el, a);
					}
				}, thr);
			} else if (trig === 'hover') {
				show(el); bindHover(el, function () { playIn(el, a); });
			} else if (trig === 'click') {
				show(el);
				var c = function () { playIn(el, a); };
				el.addEventListener('click', c); onCleanup(el, function () { el.removeEventListener('click', c); });
			}
		} else {
			show(el); afterIn();
		}

		if (a.out && a.outTrigger === 'click') {
			var oc = function () { el._msState === 'out' ? playIn(el, a) : playOut(el, a); };
			el.addEventListener('click', oc); onCleanup(el, function () { el.removeEventListener('click', oc); });
		}
		if (a.out && a.outTrigger === 'leave' && trig !== 'scroll') {
			observe(el, function (en) {
				if (!en.isIntersecting && el._msState === 'in') playOut(el, a);
				else if (en.isIntersecting && el._msState === 'out') playIn(el, a);
			}, 0);
		}
	}

	function applyRuleTo(el, rule, opts) {
		opts = opts || {};
		cleanup(el);
		if (!opts.skipContent) applyContent(el, rule.content);
		applyLink(el, rule.link);
		applyMenu(el, rule.menu);
		applyPopup(el, rule.popup);
		if (rule.video) applyVideo(el, rule.video);
		if (rule.search) applySearch(el, rule.search);
		else if (el._msSearchCfg) applySearch(el, el._msSearchCfg);
		if (rule.countdown && rule.countdown.date) el.setAttribute('data-ms-countdown', rule.countdown.date);
		if (el.hasAttribute('data-ms-countdown')) initCountdown(el);
		if (REDUCED || PHONE_OFF) { show(el); return; }
		applyFx(el, rule.fx);
		setupAnim(el, rule);
	}

	function applyRule(rule, opts) {
		qsa(rule.selector).forEach(function (el) { applyRuleTo(el, rule, opts); });
	}

	function applyAll(rules) {
		rules = rules || [];
		// Pass 1: content (so later selectors match the final DOM), pass 2: behaviour.
		rules.forEach(function (r) { if (r.content) qsa(r.selector).forEach(function (el) { applyContent(el, r.content); }); });
		rules.forEach(function (r) { applyRule(r, { skipContent: true }); });
	}

	function cleanupAll(root) {
		qsa('*', root).forEach(function (el) { if (el._msAnims || el._msClean || el._msSplit) cleanup(el); });
	}

	/* ------------------------------------------------------------------ *
	 * Structure ops – inserted blocks & moved (drag-and-drop) elements.
	 * Wrappers are <ms-block> (display:contents) so they never change the
	 * :nth-of-type index of the theme's own elements.
	 * ------------------------------------------------------------------ */
	function qs(sel) { try { return sel ? document.querySelector(sel) : null; } catch (e) { return null; } }
	function placeNode(w, anchor, pos) {
		if (pos === 'before') anchor.parentNode.insertBefore(w, anchor);
		else if (pos === 'after') anchor.parentNode.insertBefore(w, anchor.nextSibling);
		else if (pos === 'prepend') anchor.insertBefore(w, anchor.firstChild);
		else anchor.appendChild(w);
	}
	function applyOp(op) {
		if (!op || !op.id || document.getElementById(op.id)) return null;
		var anchor = op.anchor === 'body' ? document.body : qs(op.anchor);
		if (!anchor || ((op.pos === 'before' || op.pos === 'after') && !anchor.parentNode)) return null;
		var w = document.createElement('ms-block');
		w.id = op.id;
		if (op.t === 'move') {
			var el = qs(op.from);
			if (!el || el === anchor || el.contains(anchor)) return null;
			var ph = document.createElement(el.tagName);
			ph.setAttribute('data-ms-ph', '');
			ph.setAttribute('aria-hidden', 'true');
			ph.style.setProperty('display', 'none', 'important');
			el.parentNode.replaceChild(ph, el);
			w.appendChild(el);
		} else {
			w.innerHTML = op.html || '';
		}
		placeNode(w, anchor, op.pos);
		initWidgets(w);
		return w;
	}
	function applyOps(ops) { (ops || []).forEach(function (op) { try { applyOp(op); } catch (e) {} }); }


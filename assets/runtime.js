	var observers = {};
	function observe(el, cb, threshold) {
		var key = String(threshold);
		if (!observers[key]) {
			observers[key] = new IntersectionObserver(function (entries) {
				entries.forEach(function (en) { if (en.target._msIO) en.target._msIO(en); });
			}, { threshold: threshold, rootMargin: '0px 0px -5% 0px' });
		}
		el._msIO = cb;
		observers[key].observe(el);
		onCleanup(el, function () { observers[key].unobserve(el); el._msIO = null; });
	}


	var SITE = { el: {} }, lastY = 0, sraf = 0;
	function onScroll() {
		sraf = 0;
		var y = scrollY, b = document.body;
		if (!b) return;
		b.classList.toggle('ms-scrolled', y > 40);
		if (Math.abs(y - lastY) > 6) { b.classList.toggle('ms-scroll-down', y > lastY && y > 120); lastY = y; }
		if (SITE.el.progress) {
			var max = document.documentElement.scrollHeight - innerHeight;
			SITE.el.progress.style.transform = 'scaleX(' + (max > 0 ? y / max : 0) + ')';
		}
		if (SITE.el.top) SITE.el.top.classList.toggle('on', y > 600);
	}
	addEventListener('scroll', function () { if (!sraf) sraf = requestAnimationFrame(onScroll); }, { passive: true });

	function setSite(site) {
		Object.keys(SITE.el).forEach(function (k) { if (SITE.el[k] && SITE.el[k].remove) SITE.el[k].remove(); });
		if (SITE.move) removeEventListener('mousemove', SITE.move);
		SITE.el = {}; SITE.move = null;
		site = site || {};
		if (!document.body) return;
		if (site.progress) {
			var p = document.createElement('div'); p.className = 'ms-progress';
			document.body.appendChild(p); SITE.el.progress = p;
		}
		if (site.toTop) {
			var t = document.createElement('button'); t.type = 'button'; t.className = 'ms-totop'; t.setAttribute('aria-label', 'Back to top'); t.innerHTML = '&uarr;';
			t.addEventListener('click', function () { scrollTo({ top: 0, behavior: 'smooth' }); });
			document.body.appendChild(t); SITE.el.top = t;
		}
		if (site.cursor && matchMedia('(pointer:fine)').matches && !REDUCED) {
			var c = document.createElement('div'); c.className = 'ms-cursor ms-cursor-' + site.cursor;
			document.body.appendChild(c); SITE.el.cursor = c;
			var x = 0, y = 0, cx = 0, cy = 0, run = false;
			SITE.move = function (e) {
				x = e.clientX; y = e.clientY;
				c.classList.toggle('hov', !!(e.target.closest && e.target.closest('a,button,.ms-linked,[role=button]')));
				if (!run) { run = true; requestAnimationFrame(loop); }
			};
			var loop = function () {
				cx += (x - cx) * 0.25; cy += (y - cy) * 0.25;
				c.style.transform = 'translate(' + cx + 'px,' + cy + 'px)';
				if (Math.abs(x - cx) > 0.3 || Math.abs(y - cy) > 0.3) requestAnimationFrame(loop); else run = false;
			};
			addEventListener('mousemove', SITE.move);
		}
		onScroll();
	}


	function withOpacity(kf) {
		kf = kf.map(function (k) { var o = {}; for (var p in k) o[p] = k[p]; return o; });
		if (!('opacity' in kf[0])) kf[0].opacity = 0;
		if (!('opacity' in kf[kf.length - 1])) kf[kf.length - 1].opacity = 1;
		return kf;
	}
	function inKeyframes(type, d) {
		var f = IN[type] || IN.fade;
		return withOpacity(f(d));
	}
	var FLIP = { up: 'down', down: 'up', left: 'right', right: 'left' };
	function outKeyframes(type, d) {
		var name = type;
		if (/^(fade|slide)-/.test(type)) name = type.replace(/-(up|down|left|right)$/, function (m, p) { return '-' + FLIP[p]; });
		var kf = inKeyframes(IN[name] ? name : type, d).slice().reverse();
		return kf.map(function (k) {
			var o = {}; for (var p in k) o[p] = k[p];
			if ('offset' in o) o.offset = 1 - o.offset;
			return o;
		});
	}

	/* Split text into spans (letters or words), keeping inner markup. */
	function splitText(el, mode) {
		if (el._msSplit) return el._msSplit;
		el._msOrigSplit = el.innerHTML;
		var pieces = [];
		(function walk(node) {
			Array.prototype.slice.call(node.childNodes).forEach(function (n) {
				if (n.nodeType === 3) {
					var txt = n.nodeValue;
					if (!txt.trim()) return;
					var frag = document.createDocumentFragment();
					txt.split(/(\s+)/).forEach(function (p) {
						if (p === '') return;
						if (/^\s+$/.test(p)) { frag.appendChild(document.createTextNode(p)); return; }
						if (mode === 'words') {
							var w = document.createElement('span');
							w.className = 'ms-piece'; w.textContent = p;
							frag.appendChild(w); pieces.push(w);
							return;
						}
						// letters: keep each word unbreakable so lines never wrap mid-word
						var word = document.createElement('span');
						word.className = 'ms-word';
						Array.from(p).forEach(function (ch) {
							var s = document.createElement('span');
							s.className = 'ms-piece'; s.textContent = ch;
							word.appendChild(s); pieces.push(s);
						});
						frag.appendChild(word);
					});
					node.replaceChild(frag, n);
				} else if (n.nodeType === 1) {
					walk(n);
				}
			});
		})(el);
		el._msSplit = pieces;
		return pieces;
	}
	function unsplit(el) {
		if (el._msOrigSplit != null) { el.innerHTML = el._msOrigSplit; }
		el._msOrigSplit = null; el._msSplit = null;
	}


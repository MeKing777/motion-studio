	/* Block script-like addresses (javascript:, data:, vbscript:), even when hidden with spaces/control characters. */
	function safeHref(v) {
		v = String(v == null ? '' : v).trim();
		if (/^(javascript|data|vbscript):/i.test(v.replace(/[\u0000-\u0020]/g, ''))) return '';
		return v;
	}
	function linkHref(l) {
		var v = String(l.value || '').trim();
		switch (l.type) {
			case 'url': case 'page': return safeHref(v);
			case 'email': return v ? 'mailto:' + v : '';
			case 'phone': return v ? 'tel:' + v.replace(/[^\d+]/g, '') : '';
			case 'whatsapp': return v ? 'https://wa.me/' + v.replace(/\D/g, '') + (l.msg ? '?text=' + encodeURIComponent(l.msg) : '') : '';
		}
		return '';
	}
	function scrollToEl(t, off) {
		var y = t.getBoundingClientRect().top + scrollY - num(off, 80);
		scrollTo({ top: Math.max(0, y), behavior: 'smooth' });
	}
	function setOpen(t, open) {
		if (!t) return;
		var o = open == null ? !t.classList.contains('ms-open') : open;
		t.classList.toggle('ms-open', o);
		document.documentElement.classList.toggle('ms-popup-lock', !!document.querySelector('.ms-popup.ms-open'));
	}
	function applyLink(el, l) {
		if (!l || !l.type) return;
		var nav = /^(url|page|email|phone|whatsapp)$/.test(l.type);
		if (el.tagName === 'A' && nav) {
			if (el._msLinkOrig == null) el._msLinkOrig = el.getAttribute('href') || '';
			el.setAttribute('href', linkHref(l) || '#');
			if (l.newTab) { el.setAttribute('target', '_blank'); el.setAttribute('rel', 'noopener noreferrer'); }
			onCleanup(el, function () { el.setAttribute('href', el._msLinkOrig); el._msLinkOrig = null; if (l.newTab) { el.removeAttribute('target'); el.removeAttribute('rel'); } });
			return;
		}
		function act(e) {
			if (l.type === 'scroll') { e.preventDefault(); var t = qs(l.target); if (t) scrollToEl(t, l.offset); }
			else if (l.type === 'top') { e.preventDefault(); scrollTo({ top: 0, behavior: 'smooth' }); }
			else if (l.type === 'toggle') { e.preventDefault(); setOpen(qs(l.target)); }
			else if (nav) {
				var h = linkHref(l); if (!h) return;
				e.preventDefault();
				if (l.newTab) window.open(h, '_blank', 'noopener,noreferrer'); else location.href = h;
			}
		}
		function key(e) { if (e.key === 'Enter') act(e); }
		el.classList.add('ms-linked');
		if (!/^(A|BUTTON)$/.test(el.tagName)) { el.setAttribute('role', 'link'); el.tabIndex = 0; }
		el.addEventListener('click', act); el.addEventListener('keydown', key);
		onCleanup(el, function () { el.removeEventListener('click', act); el.removeEventListener('keydown', key); el.classList.remove('ms-linked'); });
	}


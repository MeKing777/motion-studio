	function applyFx(el, fx) {
		if (!fx || !fx.list || !fx.list.length) return;
		el.style.setProperty('--ms-spd', num(fx.speed, 1));
		el.style.setProperty('--ms-int', num(fx.intensity, 1));
		if (fx.color) el.style.setProperty('--ms-fxc', fx.color);
		el.classList.add('ms-fx');
		fx.list.forEach(function (t) {
			if (JS_FX[t]) { JS_FX[t](el, fx); return; }
			if (CSS_FX.indexOf(t) < 0) return;
			var cls = t;
			if (t === 'glitch' || t === 'rgb-split') {
				if (textOnly(el)) el.setAttribute('data-ms-text', el.textContent.trim().replace(/\s+/g, ' '));
				else cls = t + '-box';
			}
			el.classList.add('ms-fx-' + cls);
		});
	}

	function bindHover(el, enter, leave, moveFn) {
		var host = el;
		if (enter) host.addEventListener('mouseenter', enter);
		if (leave) host.addEventListener('mouseleave', leave);
		if (moveFn) host.addEventListener('mousemove', moveFn);
		onCleanup(el, function () {
			if (enter) host.removeEventListener('mouseenter', enter);
			if (leave) host.removeEventListener('mouseleave', leave);
			if (moveFn) host.removeEventListener('mousemove', moveFn);
		});
	}

	JS_FX.tilt = function (el, fx) {
		var max = 12 * num(fx.intensity, 1);
		el.style.transition = 'transform .15s ease-out';
		el.style.transformStyle = 'preserve-3d';
		bindHover(el, null, function () { el.style.transform = ''; }, function (e) {
			var r = el.getBoundingClientRect();
			var x = (e.clientX - r.left) / r.width - 0.5, y = (e.clientY - r.top) / r.height - 0.5;
			el.style.transform = 'perspective(900px) rotateX(' + (-y * max) + 'deg) rotateY(' + (x * max) + 'deg) scale(1.02)';
		});
	};


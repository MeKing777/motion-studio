	JS_FX.scramble = function (el, fx) {
		if (!textOnly(el)) return;
		var orig = el.textContent, chars = '!<>-_\\/[]{}—=+*^?#ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789', timer;
		function run() {
			var frame = 0, total = Math.round(28 / num(fx.speed, 1));
			clearInterval(timer);
			timer = setInterval(function () {
				var out = '';
				for (var i = 0; i < orig.length; i++) {
					out += (i < (frame / total) * orig.length || orig[i] === ' ') ? orig[i] : chars[(Math.random() * chars.length) | 0];
				}
				el.textContent = out;
				if (++frame > total) { clearInterval(timer); el.textContent = orig; }
			}, 30);
		}
		observe(el, function (en) { if (en.isIntersecting && !el._msScrambled) { el._msScrambled = 1; run(); } }, 0.3);
		bindHover(el, run);
		onCleanup(el, function () { clearInterval(timer); el.textContent = orig; el._msScrambled = 0; });
	};

	JS_FX.counter = function (el, fx) {
		var txt = el.textContent, m = txt.match(/-?[\d,]*\.?\d+/);
		if (!m) return;
		var target = parseFloat(m[0].replace(/,/g, '')), dec = (m[0].split('.')[1] || '').length;
		var pre = txt.slice(0, m.index), post = txt.slice(m.index + m[0].length), commas = m[0].indexOf(',') > -1;
		function fmt(v) { var s = v.toFixed(dec); return commas ? s.replace(/\B(?=(\d{3})+(?!\d))/g, ',') : s; }
		function run() {
			var t0 = performance.now(), dur = 1800 / num(fx.speed, 1);
			(function step(t) {
				var p = Math.min(1, (t - t0) / dur), e = 1 - Math.pow(1 - p, 3);
				el.textContent = pre + fmt(target * e) + post;
				if (p < 1) requestAnimationFrame(step);
			})(t0);
		}
		el.textContent = pre + fmt(0) + post;
		observe(el, function (en) { if (en.isIntersecting && !el._msCounted) { el._msCounted = 1; run(); } }, 0.4);
		onCleanup(el, function () { el.textContent = txt; el._msCounted = 0; });
	};


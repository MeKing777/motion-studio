	function applyContent(el, c) {
		c = c || {};
		if (c.html != null) {
			if (el._msOrigHTML == null) el._msOrigHTML = el.innerHTML;
			if (el.innerHTML !== c.html) el.innerHTML = c.html;
		} else if (el._msOrigHTML != null) { el.innerHTML = el._msOrigHTML; el._msOrigHTML = null; }

		if (el.tagName === 'IMG') {
			if (c.src) {
				if (el._msOrigSrc == null) el._msOrigSrc = { src: el.getAttribute('src'), srcset: el.getAttribute('srcset'), sizes: el.getAttribute('sizes') };
				el.removeAttribute('srcset'); el.removeAttribute('sizes'); el.removeAttribute('loading');
				if (el.getAttribute('src') !== c.src) el.setAttribute('src', c.src);
			} else if (el._msOrigSrc) {
				['src', 'srcset', 'sizes'].forEach(function (k) { if (el._msOrigSrc[k] != null) el.setAttribute(k, el._msOrigSrc[k]); });
				el._msOrigSrc = null;
			}
			if (c.alt != null) el.setAttribute('alt', c.alt);
		}
		if (el.tagName === 'A') {
			if (c.href && safeHref(c.href)) { if (el._msOrigHref == null) el._msOrigHref = el.getAttribute('href'); el.setAttribute('href', safeHref(c.href)); }
			else if (el._msOrigHref != null) { el.setAttribute('href', el._msOrigHref); el._msOrigHref = null; }
			if (c.target === '_blank') { el.setAttribute('target', '_blank'); el.setAttribute('rel', 'noopener noreferrer'); }
			else if (c.target === '_self') el.removeAttribute('target');
		}
	}

